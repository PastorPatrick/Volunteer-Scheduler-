/**
 * Combines the script files in apps-script/ into one file,
 * VolunteerScheduler.gs, so setup is a single copy and paste.
 *
 * Run after changing any script file:  node tools/build-single-file.js
 * (The tests fail if VolunteerScheduler.gs is out of date.)
 */
const fs = require('fs');
const path = require('path');

const ORDER = ['Setup.gs', 'Helpers.gs', 'Teams.gs', 'Schedule.gs', 'Pages.gs', 'Elvanto.gs', 'Twilio.gs'];
const dir = path.join(__dirname, '..', 'apps-script');

function buildSingleFile() {
  const header = [
    '/**',
    ' * VOLUNTEER SCHEDULER: all-in-one script',
    ' *',
    ' * Paste this whole file into Extensions → Apps Script (replacing Code.gs) and click Save.',
    ' * It is the files in the apps-script folder joined together, generated by',
    ' * tools/build-single-file.js. The sections below are marked with the original file names.',
    ' */',
    '',
  ].join('\n');
  return header + ORDER.map((f) =>
    '\n// ##########################################################\n' +
    '// ' + f + '\n' +
    '// ##########################################################\n\n' +
    fs.readFileSync(path.join(dir, f), 'utf8')).join('\n');
}

module.exports = { buildSingleFile, ORDER };

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, '..', 'VolunteerScheduler.gs'), buildSingleFile());
  console.log('Wrote VolunteerScheduler.gs');
}
